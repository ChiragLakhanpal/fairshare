// Every string a person reads, as full sentences a 10th grader follows. Buttons stay short verb phrases.
const WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];
export const numberWord = (n: number): string => (Number.isInteger(n) && n >= 0 && n <= 10 ? WORDS[n] : String(n));
export const capital = (s: string): string => (s ? s[0].toUpperCase() + s.slice(1) : s);
/** About half a minute per item: "a minute", "two minutes". */
export const minutesWord = (items: number): string => {
  const m = Math.max(1, Math.round(items / 2));
  return m === 1 ? "a minute" : `${numberWord(m)} minutes`;
};

